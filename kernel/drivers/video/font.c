uint8_t font_glyph_row(unsigned char character, size_t row)
{
    if (row >= UTAMO_FONT_HEIGHT) {
        return 0u;
    }
    if (character < 0x20u || character > 0x7eu) {
        character = (unsigned char)'?';
    }
    return ascii_glyphs[(size_t)character - 0x20u][row];
}
